const mongoose = require('mongoose');

const LocalizedTextSchema = new mongoose.Schema(
  {
    en: {
      type: String,
      required: [true, 'Please provide English text'],
      trim: true,
    },
    es: {
      type: String,
      default: '',
      trim: true,
    },
  },
  { _id: false }
);

const NotificationSchema = new mongoose.Schema(
  {
    recipient: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: [true, 'Recipient user is required'],
      index: true,
    },
    sender: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      default: null, // Null if generated by system
    },
    title: {
      type: LocalizedTextSchema,
      required: [true, 'Please provide a notification title'],
      set: function (val) {
        if (typeof val === 'string') {
          return { en: val, es: val };
        }
        return val;
      },
    },
    message: {
      type: LocalizedTextSchema,
      required: [true, 'Please provide a notification message'],
      set: function (val) {
        if (typeof val === 'string') {
          return { en: val, es: val };
        }
        return val;
      },
    },
    type: {
      type: String,
      enum: {
        values: [
          'PROPERTY_MATCH',   // New property matching saved search filters
          'PRICE_DROP',       // Price drop on favorite/saved property
          'LEAD_RECEIVED',    // New lead received for an agent
          'LEAD_SENT',        // Lead successfully sent confirmation for buyer
          'LEAD_UPDATE',      // Status update on a lead
          'AGENT_REGISTRATION', // New agent registered, awaiting admin approval
          'AGENT_APPROVAL',   // Agent approval / status change notification
          'PLAN_UPGRADE',     // Agent tier plan upgrade notification
          'SYSTEM_ALERT',     // System announcements or account updates
          'GENERAL',          // General notifications
        ],
        message: 'Invalid notification type',
      },
      default: 'GENERAL',
    },
    // Related entities / payload details for navigation and context
    data: {
      property: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'Property',
        default: null,
      },
      lead: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'Lead',
        default: null,
      },
      savedSearch: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'SavedSearch',
        default: null,
      },
      link: {
        type: String,
        trim: true,
        default: null,
      },
      metadata: {
        type: mongoose.Schema.Types.Mixed,
        default: {},
      },
    },
    isRead: {
      type: Boolean,
      default: false,
      index: true,
    },
    readAt: {
      type: Date,
      default: null,
    },
  },
  {
    timestamps: true,
  }
);

// Compound index for querying a user's unread / recent notifications efficiently
NotificationSchema.index({ recipient: 1, isRead: 1, createdAt: -1 });
NotificationSchema.index({ recipient: 1, createdAt: -1 });

module.exports = mongoose.model('Notification', NotificationSchema);
